"""Infer visible rotational sections from contour slopes at the fixed angle.

This is a diagnostic inverse-envelope estimate, not recovery of hidden shape.
Test its assumptions against actual saved-mesh tangent probes before interpreting
the low-resolution sources. Discontinuities and blur invalidate local inversion.
"""
from pathlib import Path
import json
import math
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
out = ROOT / 'build/bishop-mission/178-contour-audit'
capture = json.loads((out / 'meridians.json').read_text())
al = json.loads((ROOT / 'assets/bishop/original-alignment.json').read_text())
F = 1254 / 300 / al['scale']; sn = math.sin(math.radians(54))
captured = {r['pixel_y']: r for r in capture['rows']}
def inverse_section(y, half_width, slope):
    return {'profile_radius': float(half_width * math.sqrt(1 + sn**2 * slope**2) / F),
            'profile_axis_y': float((y + sn**2 * half_width * slope) / F + al['y'] * 3)}
validation = []
for y, row in captured.items():
    region = row['sides']['right']['region']
    nearby = [r for yy, r in captured.items() if abs(yy-y) <= 10 and r['sides']['right']['region'] == region]
    if len(nearby) < 9: continue
    v = np.array([r['pixel_y'] - y for r in nearby])
    hw = np.array([(r['sides']['right']['pixel_x'] - r['sides']['left']['pixel_x']) / 2 for r in nearby])
    coeff = np.polynomial.polynomial.polyfit(v, hw, 3)
    inferred = inverse_section(y, coeff[0], coeff[1])
    measured = row['sides']['right']
    validation.append({'pixel_y': y, 'region': region, 'inferred': inferred,
        'measured': {k: measured[k] for k in ['profile_radius', 'profile_axis_y']},
        'radius_error': inferred['profile_radius'] - measured['profile_radius'],
        'axis_y_error': inferred['profile_axis_y'] - measured['profile_axis_y']})
images = {}
for name, path, alignment in [('original_white', 'original.png', 'original-alignment.json'),
                               ('original_black', 'black-original.png', 'black-alignment.json'),
                               ('selected_white_3', 'reference.png', None)]:
    im = Image.open(ROOT / 'assets/bishop' / path).convert('RGBA')
    if alignment:
        a = json.loads((ROOT / 'assets/bishop' / alignment).read_text()); s = a['scale'] * 300 / 1254
        im = im.transform((1254, 1254), Image.Transform.AFFINE,
            (s, 0, a['x']*3, 0, s, a['y']*3), Image.Resampling.BILINEAR)
    arr = np.array(im); mask = (arr[:, :, 3] > 127) & (arr[:, :, :3].max(2) > 12)
    widths = {y: (lambda xs: (xs[-1]-xs[0]+1)/2)(np.flatnonzero(mask[y])) for y in range(575, 821)}
    values = []
    for y in [601, 605, 609, 613, 617, 621, 629, 637, 645, 661, 685, 713, 745]:
        estimates = []
        for half_window in [6, 10, 14]:
            ys = np.arange(y-half_window, y+half_window+1)
            coeff = np.polynomial.polynomial.polyfit(ys-y, [widths[int(t)] for t in ys], 3)
            estimates.append(dict(half_window=half_window, half_width=float(coeff[0]), slope=float(coeff[1]),
                                 **inverse_section(y+.5, coeff[0], coeff[1])))
        values.append({'pixel_y': y+.5, 'estimates': estimates,
                       'near_current_surface_switch': 615 <= y <= 638})
    images[name] = values
report = {'camera_degrees': 54, 'model_sha256': capture['source_sha256'],
    'formula': 'v = y + sin(e)^2 * x * dx/dy; r = x*sqrt(1+sin(e)^2*(dx/dy)^2), then convert pixels to profile coordinates.',
    'derivation': 'Differentiate the envelope x^2 = r(v)^2 - ((y-v)/sin(e))^2 at a tangent circle.',
    'model_validation': validation,
    'model_median_absolute_radius_error': float(np.median([abs(r['radius_error']) for r in validation])),
    'model_median_absolute_axis_y_error': float(np.median([abs(r['axis_y_error']) for r in validation])),
    'source_estimates': images,
    'limitation': 'Valid only for a smooth rotational silhouette generated by one surface. Original edges are blurred and quantized; collar/stem/base occlusion switches break the local assumption. Window variation is a sensitivity check, not a confidence interval. Do not fit hidden surfaces or change registration from these estimates.'}
(out / 'inverse-sections.json').write_text(json.dumps(report, indent=2) + '\n')
print(json.dumps({k: report[k] for k in ['model_median_absolute_radius_error', 'model_median_absolute_axis_y_error']}, indent=2))
for name, rows in images.items():
    print(name, json.dumps([{'y': r['pixel_y'], 'radius': r['estimates'][1]['profile_radius'],
                            'axis_y': r['estimates'][1]['profile_axis_y']} for r in rows[:6]]))
